let currentLang = localStorage.getItem('krishi_lang') || 'en';

function t(key) {
  return translations[currentLang][key] || translations['en'][key] || key;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('krishi_lang', lang);
  applyTranslations();
  // Update toggle button text
  const btn = document.getElementById('langToggle');
  if (btn) btn.textContent = lang === 'en' ? 'हिंदी' : 'English';
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang][key]) {
      el.textContent = translations[currentLang][key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[currentLang][key]) {
      el.placeholder = translations[currentLang][key];
    }
  });
}

function getCurrentLang() { return currentLang; }

// Extensibility: addLanguage('mr', { ... })
function addLanguage(code, dict) {
  translations[code] = dict;
}

document.addEventListener('DOMContentLoaded', () => {
  currentLang = localStorage.getItem('krishi_lang') || 'en';
  applyTranslations();
  const btn = document.getElementById('langToggle');
  if (btn) {
    btn.textContent = currentLang === 'en' ? 'हिंदी' : 'English';
    btn.addEventListener('click', () => {
      setLanguage(currentLang === 'en' ? 'hi' : 'en');
    });
  }
});
